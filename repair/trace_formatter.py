def format_STOREs(row, r):
    # Store: 0xb82306 Size: 2 ID: 2862 @Ln,Col: 564,22 Scope: insert_key; <Thread ID:140255810307904>
    stmt = []
    scope = str(row).split(" ")[9].replace(";", "")
    add = str(row).split(" ")[1]
    tid = str(row).split(":")[-1].split(">")[0]
    line = row.split("@")[1].split(":")[1].split(",")[0].strip()
    uid = str(row).split(" ")[5]
    stmt = [r, "STORE", add, tid, uid, scope+"_"+line]
    return stmt

def format_FLUSH(row, r):
    # CLFLUSH: 0x7f1c502a4dd0 LEN: 16 @Ln,Col: 248,3 ; Scope: Insert;  <Thread ID:139759524288256>
    stmt = []
    scope = str(row).split(" ")[8].replace(";", "")
    add = str(row).split(" ")[1]
    tid = str(row).split(":")[-1].split(">")[0]
    line = row.split("@")[1].split(":")[1].split(",")[0].strip()
    stmt = [r, "FLUSH", add, tid, scope+"_"+line]
    return stmt

def format_FENCE(row, r):
    # SFENCE. @Ln,Col: 245,3 ; Scope: Insert;  <Thread ID:139759532680960>
    stmt = []
    scope = str(row).split(" ")[5].replace(";", "")
    tid = str(row).split(":")[-1].split(">")[0]
    line = row.split("@")[1].split(":")[1].split(",")[0].strip()
    stmt = [r, "FENCE", 0, tid, scope+"_"+line]
    return stmt

def format_Transactions(row, r):
    # Transaction Commits. @Ln,Col: 355,3 Scope: commit; <Thread ID:139888889608256>
    # Transaction begins. @Ln,Col: 110,8 Scope: manual<>; <Thread ID:139888889608256>
    
    stmt = []
    scope = str(row).split(" ")[5].replace(";", "")
    tid = str(row).split(":")[-1].split(">")[0]
    line = row.split("@")[1].split(":")[1].split(",")[0].strip()
    if "Transaction begins" in str(row):
        stmt = [r, "tx_begin", 0, tid, scope+"_"+line]
    else:
        stmt = [r, "tx_commit", 0, tid, scope+"_"+line]
    return stmt

def fileReader(name):
    f = open(name)
    contents = []
    loads = {}
    dependencies = {}
    r = 0
    rows = []
    for row in f:
        rows.append(row)

    for i in range(len(rows)):
        row = rows[i]
        r += 1
        if "Load" in str(row):
            dest = str(row).split(" ")[5]
            source = ""
            for j in range(0, i):
                if "Store" in str(rows[j]) and str(rows[i]).split(" ")[1]==str(rows[j]).split(" ")[1]:
                    source = str(rows[j]).split(" ")[5]
                    # print(source, dest)
            if source!="":
                dependencies[dest] = source
            if source!="":
                stmt = format_STOREs(str(row), r) # Added this only to get MPAs in CCEH. But, no real MPAs exist in CCEH. Hence, commenting out.
                contents.append(stmt)

        if "Load" in str(row) or "Store" in str(row):
            # print(row)
            stmt = []
            # Load: 0xb82308 Size: 8 ID: 733 @Ln,Col: 573,11 Scope: store; <Thread ID:140255810307904>
            scope = str(row).split(" ")[9].replace(";", "_")
            add = str(row).split(" ")[1]
            tid = str(row).split(":")[-1].split(">")[0]
            line = row.split("@")[1].split(":")[1].split(",")[0].strip()
            uid = str(row).split(" ")[5]
            stmt = [r, "LOAD", add, tid, scope+line]
            if uid=="103" or uid==103:
                print("YES")
            if uid not in loads.keys():
                loads[uid] = stmt
            stmt = format_STOREs(str(row), r)
            contents.append(stmt)

        if "Store" in str(row):
            stmt = format_STOREs(str(row), r)
            contents.append(stmt)
            
        elif "FLUSH" in str(row):
            stmt = format_FLUSH(str(row), r)
            contents.append(stmt)
        
        elif "FENCE" in str(row):
            stmt = format_FENCE(str(row), r)
            contents.append(stmt)
        
        elif "Transaction" in str(row):
            stmt = format_Transactions(str(row), r)
            contents.append(stmt)
        
        elif "DEP" in str(row):
            source = str(row).split(" ")[2]
            dest = str(row).split(" ")[4].split(";")[0]
            dependencies[dest] = source
    
    # print(loads.keys())
    print("Total number of lines:", r)
    return contents, dependencies, loads

def getThreads(trace):
    threads = {}
    c = 0
    for t in trace:
        # print(t)
        if t[3] not in threads.keys():
            threads[t[3]] = c
            c += 1
    return threads

def format(trace, threads, dependencies, loads):
    # print(loads)
    traceFormatted = []
    dep = 0
    dep_set = []
    for i in range(len(trace)):
        element = []
        # print(i)
        if trace[i][1]=='LOAD':
            continue
        if trace[i][1] in ['FLUSH', 'FENCE']:
            element = [trace[i][0], trace[i][1], trace[i][2], -1, threads[trace[i][3]], trace[i][-1]]
        elif trace[i][1] in ['tx_begin', 'tx_commit']:
            element = [trace[i][0], trace[i][1], trace[i][2], -1, threads[trace[i][3]], trace[i][-1]]
        
        elif trace[i][1]=='STORE':
            element = [trace[i][0], trace[i][1], trace[i][2], -1, threads[trace[i][3]]]
            if trace[i][-2] in dependencies.keys():
                dest_id = dependencies[trace[i][-2]]
                if dest_id in loads.keys():
                    element[3] = loads[dest_id][2]
                    dep += 1
                    if [trace[i], loads[dest_id]] not in dep_set:
                        dep_set.append([trace[i], loads[dest_id]])
            element.append(trace[i][-1])
            
        traceFormatted.append(element[1:])

    print(len(traceFormatted))
    print("Total unique dependencies: ", len(dep_set))
    print("Total dependencies: ", dep)
        
    # toreturn = []
    # for t in traceFormatted:
    #     toreturn.append(t[1:])
    
    return traceFormatted

def removeDuplicates(trace):
    traceToSend = [trace[0]]
    for i in range(1, len(trace)):
        if str(trace[i])!=str(traceToSend[-1]) and "Node" not in str(trace[i]):
            traceToSend.append(trace[i])
    
    return traceToSend

